"""Emit the bold redraw of the original logo into wwwroot/brand/."""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sketch as K
import build as B

OUT = r"C:\Users\hakan\Documents\Mekanika\wwwroot\brand"
os.makedirs(OUT, exist_ok=True)
HEAD = ("<!-- Mekanika logo. Generated by docs/design-assets/logo/2026-11-redraw/build.py"
        " - do not hand-edit. -->\n")

INK, PAPER, ACC = K.INK, "#ffffff", K.ACC
DARK = "#2b3550"


def aspect(svg):
    vb = re.search(r'viewBox="([^"]+)"', svg).group(1).split()
    return float(vb[2]) / float(vb[3])


files = {
    # wordmark alone - the sidebar, and anywhere under ~240px where the dimension
    # lines would be two hairlines and a smudge
    "wordmark.svg":         B.plain("wm", INK, PAPER),
    "wordmark-on-dark.svg": B.plain("wmd", PAPER, DARK),
    # the default lockup: wordmark between its two dimension lines
    "logo.svg":         B.compact("lg", INK, PAPER, ACC),
    "logo-on-dark.svg": B.compact("lgd", PAPER, DARK, ACC),
    # the full drawing - gears, ruler, compass, rotation arrows. Hero, share card,
    # print; it needs real width to hold together
    "logo-full.svg":         B.full("fl", INK, PAPER, ACC),
    "logo-full-on-dark.svg": B.full("fld", PAPER, DARK, ACC),
    # square mark
    "mark.svg":         B.mark("mk", INK, PAPER, ACC),
    "mark-on-dark.svg": B.mark("mkd", PAPER, DARK, ACC),
}

# The favicon's M is SOLID, not hatched. At 16px the knocked-out hatch lines are
# sub-pixel and turn the letter into grey noise; everywhere else the hatch is the
# whole point, so the two files legitimately differ.
m = B._poly_m()
files["favicon.svg"] = (
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">'
    '<style>'
    '.plate{fill:#2b3550}.m{fill:#ffffff}'
    '@media (prefers-color-scheme:dark){.plate{fill:#ffffff}.m{fill:#2b3550}}'
    '</style>'
    '<rect class="plate" x="2" y="2" width="96" height="96" rx="20"/>'
    f'<g transform="translate(22.56 22.00) scale(0.56)"><path class="m" d="{m}"/></g>'
    '<path d="M34 86 H66" stroke="#e07a30" stroke-width="6" stroke-linecap="round"/>'
    '</svg>')

for name, svg in files.items():
    with open(os.path.join(OUT, name), "w", encoding="utf-8") as f:
        f.write(HEAD + svg + "\n")

for n in ("wordmark.svg", "logo.svg", "logo-full.svg", "mark.svg"):
    a = aspect(files[n])
    print(f"{n:24s} aspect {a:.4f}   200px -> {200/a:6.1f}   300px -> {300/a:6.1f}")
